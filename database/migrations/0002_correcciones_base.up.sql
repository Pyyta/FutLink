-- 0002 · Correcciones fundacionales detectadas contra el esquema real.
-- Solo usa ALTER/ADD no destructivos. Las tablas están vacías hoy, pero el orden
-- está pensado para funcionar sobre datos existentes cuando aplique.

-- 1) Correo único sin distinguir mayúsculas (RF-01). Falla con mensaje claro si ya
-- existieran duplicados que difieran solo en mayúsculas.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM users
    GROUP BY lower(email)
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION
      'Hay correos duplicados sin distinguir mayúsculas. Corrígelos antes de aplicar 0002.';
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key ON users (lower(email));

-- 2) bcrypt produce hashes de 60 caracteres; varchar(16) los truncaría (RNF-04).
ALTER TABLE users ALTER COLUMN password TYPE varchar(72);

-- 3) El registro de Figma no captura fecha de nacimiento; se deja opcional.
ALTER TABLE users ALTER COLUMN birthdate DROP NOT NULL;

-- 4) Foto de perfil y fecha de actualización (RF-02, RF-03, RF-09).
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_pic text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

-- 5) Estados y roles válidos (RF-11, borrado suave aprobado).
ALTER TABLE users
  ADD CONSTRAINT users_role_check CHECK (role IN ('user', 'admin'));
ALTER TABLE users
  ADD CONSTRAINT users_state_check CHECK (state IN ('active', 'suspended', 'deleted'));

-- 6) positions no tenía PK ni generación automática de id. Se conserva la FK de
-- userspositions: se retira, se reemplaza el UNIQUE por la PK y se vuelve a crear.
ALTER TABLE userspositions
  DROP CONSTRAINT IF EXISTS userspositions_id_positions_fkey;
ALTER TABLE positions
  DROP CONSTRAINT IF EXISTS positions_id_key;
ALTER TABLE positions
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE positions
  ADD CONSTRAINT positions_pkey PRIMARY KEY (id);
ALTER TABLE userspositions
  ADD CONSTRAINT userspositions_id_positions_fkey
  FOREIGN KEY (id_positions) REFERENCES positions(id) ON DELETE CASCADE;

-- Necesario para los seeds idempotentes con ON CONFLICT (title).
CREATE UNIQUE INDEX IF NOT EXISTS positions_title_key ON positions (title);

-- Si ya hubiera filas, el siguiente id continúa después del máximo existente.
SELECT setval(
  pg_get_serial_sequence('positions', 'id'),
  COALESCE((SELECT max(id) FROM positions), 0) + 1,
  false
);

-- 7) Catálogo de localidades de Bogotá D.C. para RF-02, RF-04 y RF-14.
CREATE TABLE IF NOT EXISTS localities (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  CONSTRAINT localities_name_key UNIQUE (name)
);
